// Copies a curated set of Lucide icons (ISC license) into src/engine/icons.ts, so the app
// doesn't ship all 2,000+ icons. The same names go into the template catalog the AI picks from.
// Run: node scripts/build-icons.cjs
const lucide = require("lucide");
const fs = require("fs");
const path = require("path");
const NAMES = [
  "Scale", "Gavel", "Landmark", "ScrollText", "FileText", "BookOpen", "Vote", "Users", "User", "Crown",
  "Flag", "Shield", "ShieldCheck", "Lock", "Key", "Clock", "Calendar", "Hourglass", "Timer", "Check",
  "X", "CircleCheck", "CircleX", "TriangleAlert", "Info", "Lightbulb", "Sparkles", "Star", "Heart", "Zap",
  "Flame", "Rocket", "Target", "TrendingUp", "TrendingDown", "ChartBar", "ChartPie", "DollarSign", "Coins", "Wallet",
  "Building", "Building2", "House", "Globe", "Map", "MapPin", "Mail", "MessageCircle", "Megaphone", "Mic",
  "Camera", "Video", "Music", "Headphones", "Laptop", "Smartphone", "Cpu", "Code", "Brain", "Eye",
  "Search", "Hand", "ThumbsUp", "ThumbsDown", "Handshake", "Swords", "Trophy", "Gift", "Pencil", "Signature",
  "Stamp", "Ban", "Repeat", "ArrowRight", "ArrowUp", "ArrowDown", "Plus", "Minus", "Equal", "Percent",
];
const out = {};
for (const n of NAMES) {
  const node = lucide[n];
  if (!node) throw new Error(`Unknown Lucide icon: ${n}`);
  out[n] = node;
}
const body = `// Generated by scripts/build-icons.cjs from Lucide (ISC license). Do not edit by hand.
export type IconNode = [string, Record<string, string | number>][];
export const ICONS: Record<string, IconNode> = ${JSON.stringify(out)};
export const ICON_NAMES = Object.keys(ICONS);
`;
fs.writeFileSync(path.join(__dirname, "../src/engine/icons.ts"), body);
fs.writeFileSync(path.join(__dirname, "../../../packages/shared/icon-names.json"), JSON.stringify(NAMES, null, 1));
console.log(`Wrote ${NAMES.length} icons`);
